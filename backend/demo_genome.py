BUNDLED_GENOMES: Dict[str, BundledGenome] = {
    DEMO_GENOME.genome_id: DEMO_GENOME,
    SLICE_GENOME.genome_id: SLICE_GENOME,
}

BUNDLED_SPECIES_KEYS = frozenset(genome.species_key for genome in BUNDLED_GENOMES.values())


def bundled_genome(genome_id: Any = None) -> BundledGenome:
    """Look one up, defaulting to the demo genome so old callers keep working."""
    key = str(genome_id or "").strip() or DEMO_GENOME_ID
    genome = BUNDLED_GENOMES.get(key)
    if genome is None:
        raise ValueError(f"Unknown bundled genome: {key}")
    return genome


