"""The little genomes the tutorials install.

Teaching someone the download view is awkward: a real assembly is gigabytes and needs a
network. So the tutorials ship their own, and there are two of them, because they teach
different things.

*Ensemblus welcomus* — twenty-two kilobases of invented sequence across two contigs, with
genes called Welcome, To, Ensembl and Go — is for **Getting Started**, where the point is
the shape of the workflow and the genome is only something to carry through it.

The **GRCh38 REG4 slice** is for the browser tutorial, where the genome *is* the subject:
half a megabase of real chromosome 1 with its real Ensembl annotation, so there are genes
with thirty-eight transcripts to flatten, four gene classes to filter, and sequence worth
zooming into. Its coordinates are the true ones — the FASTA record is chromosome ``1``
with ``N`` in front of the window — so REG4 answers at 1:119,794,017 here exactly as it
does on the Ensembl website.

Installing either means copying its files into the same ``local_data`` layout a download
produces, under the same naming rules, with the same manifest. Nothing downstream knows
or cares that they arrived differently: they list, index, browse, and — because their
files carry the accession prefix that marks a file as ours — delete through the ordinary
genome-removal UI.

The files themselves are generated by ``scripts/build_demo_genome.py`` and
``scripts/build_grch38_slice.py``.
"""

from __future__ import annotations

import json
import shutil
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

from genome_identity import DEFAULT_PROVIDER, genome_manifest_filename


@dataclass(frozen=True)
class BundledGenome:
    """One genome that ships with the app rather than being downloaded.

    Everything a caller needs to install it, list it and browse it. It exists because
    there are two of these now and every one of the values below used to be a module
    constant — which worked exactly until there was a second genome.
    """

    genome_id: str
    source_dir_name: str
    species_key: str
    assembly: str
    assembly_name: str
    scientific_name: str
    common_name: str
    display_name: str
    # A URL scheme that is obviously not a download, but is non-empty — which is what
    # marks the files as ours to delete rather than as something the user brought in.
    # See ``main._is_download_managed_assembly``.
    url_scheme: str
    # source filename -> (path within the assembly directory, file type). The accession
    # prefix is what ``main._downloaded_assembly_files`` looks for, so it is not
    # decoration. A file type of "" is a sidecar: copied, but not a file in its own right.
    files: Dict[str, Tuple[str, str]]
    # Region -> (start, end) that is worth looking at, when that is narrower than the
    # region itself. The chromosome-1 slice is a real chromosome coordinate space with a
    # small window of real sequence in it, so without this the browser lets you pan out
    # into a hundred megabases of padding — which reads as the app being broken rather
    # than as the edge of a slice. Surfaced by /api/browse/regions and enforced by the
    # browser's own clampView; absent for everything else, which is unaffected.
    browsable_range: Dict[str, Tuple[int, int]] = field(default_factory=dict)
    blurb: str = ""
    provider: str = DEFAULT_PROVIDER
    # The annotation goes in a dataset release of its own rather than loose in the
    # assembly directory. Loose annotations are swept into the "legacy/unknown" bucket,
    # which the UI quite reasonably labels "Legacy local files" — true of a genome someone
    # copied in by hand years ago, and wrong for these. A real release also matches what a
    # download produces.
    release_source: str = "demo"
    release_date: str = "current"
    release_label: str = "Demo"

    @property
    def release_key(self) -> str:
        return f"{self.release_source}/{self.release_date}"

    @property
    def annotation_path(self) -> str:
        """Where the GFF3 lands inside the assembly directory."""
        for installed_path, file_type in self.files.values():
            if file_type == "gff3":
                return installed_path
        raise KeyError(f"{self.genome_id} bundles no annotation")


